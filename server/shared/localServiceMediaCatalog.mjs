/**
 * Retorna as mídias locais canônicas cadastradas para uma determinada chave de serviço.
 * @param {string} serviceKey
 * @returns {Array}
 */
export function getLocalMediaForService(serviceKey) {
  if (!serviceKey || typeof serviceKey !== 'string') return []
  const normalizedKey = serviceKey.trim()
  return LOCAL_SERVICE_MEDIA.filter(item => item.service_key === normalizedKey)
}
